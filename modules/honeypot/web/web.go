// Package web 是**Web 诱饵场景包**：一个独立的后端，服务一套**合成**的管理台场景
// （登录页 → 合成演示会话 → 假配置 / 用户列表 / 审计日志 / 分页 API）。
//
// 它在方案里的位置：`C03`（Web/admin 仿真，P1）+ `C04`（数据伪装：同一场景包内标识、数量、
// 分页关系一致）。它**不是**核心的一部分（`AR-2`：判定只在核心），也**不实现真蜜罐**：
// 它是 `honeypot` 契约里一个**可替换的后端**（[ADR-0011](../../docs/background/decisions/0011-honeypot-entry-external-backends.md)），
// 由核心的诱饵路由表（`decoys` 段）指过来。
//
// 四条硬边界（都在代码里落地，并有单测）：
//
//	① **不用生产认证**：登录**从不校验真实凭据**，也从不调用任何认证服务；
//	   请求里的密码字段**默认丢弃**（不入日志、不入页面、不入事件）；
//	② **只有合成数据**：组织 / 版本 / 账号 / 目录 / 审计事件全部是虚构素材（`.example` 域，
//	   占位密钥，无真实密钥与个人信息）—— 场景数据**确定性**生成（同场景恒同数据，`AR-30` 的精神）；
//	③ **隔离与配额**：请求体有上限（超限 413），服务**不发起任何出站连接**，只监听本机；
//	④ **只走专属路径**：它假设自己被挂在「专属诱饵路由」后面；若路由未接，它也不会回源业务
//	   （那是适配器的 `deliverDecoy` 的职责：故障固定 502、不回生产）。
